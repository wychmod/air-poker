import { mkdir, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

// Original deterministic ambient score. No samples or downloaded tracks.
const sr = 48000,
  seconds = 30,
  n = sr * seconds;
const output = resolve(import.meta.dirname, '../public/audio');
await mkdir(output, { recursive: true });
const samples = new Float64Array(n * 2);
const note = (midi) => 440 * 2 ** ((midi - 69) / 12);
const chords = [
  [38, 45, 50, 57],
  [34, 41, 46, 53],
  [36, 43, 48, 55],
  [38, 45, 50, 57],
];
let seed = 731209,
  low = 0;
function noise() {
  seed = (Math.imul(seed, 1664525) + 1013904223) >>> 0;
  return (seed / 4294967296) * 2 - 1;
}
function smooth(x) {
  x = Math.max(0, Math.min(1, x));
  return x * x * (3 - 2 * x);
}
for (let i = 0; i < n; i++) {
  const t = i / sr;
  const intro = smooth(t / 1.2),
    outro = smooth((seconds - t) / 2.7);
  const section = Math.min(3, Math.floor(t / 7.5));
  const q = smooth((t % 7.5) / 1.6);
  const prev = chords[Math.max(0, section - 1)],
    curr = chords[section];
  let l = 0,
    r = 0;
  for (let k = 0; k < 4; k++) {
    const oldF = note(prev[k]),
      f = note(curr[k]);
    const amplitude = (0.09 / (1 + k * 0.42)) * (1 + 0.12 * Math.sin(t * 0.68 + k));
    l +=
      amplitude * ((1 - q) * Math.sin(2 * Math.PI * oldF * t) + q * Math.sin(2 * Math.PI * f * t));
    r +=
      amplitude *
      ((1 - q) * Math.sin(2 * Math.PI * oldF * t + 0.23 * k) +
        q * Math.sin(2 * Math.PI * f * t + 0.23 * k));
    l += amplitude * 0.16 * Math.sin(2 * Math.PI * f * 2 * t + 0.3);
    r += amplitude * 0.16 * Math.sin(2 * Math.PI * f * 2 * t + 0.6);
  }
  const step = Math.floor(t / 1.5),
    local = t - step * 1.5;
  const melody = [62, 69, 65, 64, 62, 57, 60, 65, 62, 69, 70, 69, 65, 62, 60, 57, 62, 65, 69, 74];
  const env = smooth(local / 0.06) * Math.exp(-local * 2.2);
  const m = note(melody[step % melody.length]);
  const pluck =
    0.035 * env * (Math.sin(2 * Math.PI * m * local) + 0.2 * Math.sin(2 * Math.PI * m * 2 * local));
  low = 0.993 * low + 0.007 * noise();
  const bed = low * 0.18 * (0.7 + 0.3 * Math.sin(t * 0.55));
  samples[2 * i] = (l + pluck + bed) * intro * outro;
  samples[2 * i + 1] = (r + pluck * 0.8 + bed) * intro * outro;
}
let peak = 0;
for (const s of samples) peak = Math.max(peak, Math.abs(s));
const gain = 10 ** (-5 / 20) / peak;
const wav = Buffer.alloc(44 + n * 4);
wav.write('RIFF', 0);
wav.writeUInt32LE(wav.length - 8, 4);
wav.write('WAVEfmt ', 8);
wav.writeUInt32LE(16, 16);
wav.writeUInt16LE(1, 20);
wav.writeUInt16LE(2, 22);
wav.writeUInt32LE(sr, 24);
wav.writeUInt32LE(sr * 4, 28);
wav.writeUInt16LE(4, 32);
wav.writeUInt16LE(16, 34);
wav.write('data', 36);
wav.writeUInt32LE(n * 4, 40);
for (let i = 0; i < n * 2; i++) wav.writeInt16LE(Math.round(samples[i] * gain * 32767), 44 + i * 2);
await writeFile(resolve(output, 'air-poker-score.wav'), wav);
await writeFile(
  resolve(output, 'audio-manifest.json'),
  JSON.stringify(
    {
      file: 'air-poker-score.wav',
      seconds,
      sampleRate: sr,
      channels: 2,
      sha256: createHash('sha256').update(wav).digest('hex'),
      source:
        'Original deterministic procedural score, generated by scripts/audio.mjs; no sampled or external audio.',
      composition:
        'Ambient minor-key pad with soft melodic notes and filtered-noise bed. No strong drum grid.',
      seed: 731209,
      pcmPeakDb: -5,
      renderVolume: 0.72,
      sfx: [],
      freesound:
        'Search was rate-limited; no external SFX downloaded or used. Search responses retained in project root.',
    },
    null,
    2,
  ),
);
console.log('Generated original stereo score: 30s / 48kHz, PCM peak -5 dBFS.');
