export function translate(lang, key, values = {}) {
  const text = I18N[lang]?.[key] ?? I18N.zh[key] ?? key;
  return Object.entries(values).reduce(
    (result, [name, value]) => result.replaceAll(`{${name}}`, value),
    text,
  );
}

export function pageCopy(lang, key) {
  return PAGE_COPY[lang]?.[key] ?? PAGE_COPY.zh[key] ?? key;
}

export function isLanguage(lang) {
  return Object.hasOwn(I18N, lang);
}
